def _fmt(text: str, db=None) -> str:
    """Подстановка оператора, почты и названия продукта в пункт документа."""
    req = consent.requisites(db)
    return text.format(
        operator=consent.operator_line(db),
        contact=req["contact"] or CONTACT_DEFAULT,
        product=PRODUCT,
        name=consent.OPERATOR_NAME,
    )


def sections(db=None) -> list[dict]:
    """Разделы Оферты с подставленными реквизитами, почтой и названием."""
    return [{"n": s["n"], "title": _fmt(s["title"], db),
             "clauses": [_fmt(c, db) for c in s["clauses"]]} for s in SECTIONS]


def definitions(db=None) -> list[dict]:
    """Термины и определения раздела 1."""
    return [{"term": t, "text": _fmt(v, db)} for t, v in DEFINITIONS]


def preamble(db=None) -> list[str]:
    return [_fmt(p, db) for p in PREAMBLE]


def requisites_block(db=None) -> dict:
    """Раздел 19: реквизиты Правообладателя либо пояснение об их отсутствии."""
    req = consent.requisites(db)
    complete = consent.requisites_complete(db)
    lines = [consent.operator_line(db)]
    if req["inn"]:
        lines.append("ИНН " + req["inn"])
    if req["ogrn"]:
        lines.append("ОГРН " + req["ogrn"])
    if req["address"]:
        lines.append("Адрес: " + req["address"])
    lines.append("Электронная почта: " + (req["contact"] or CONTACT_DEFAULT))
    return {
        "n": "19",
        "title": "Реквизиты Правообладателя",
        "complete": complete,
        "lines": lines if complete else [],
        "note": "" if complete else _fmt(REQUISITES_PENDING, db),
    }


def full_text(db=None) -> str:
    """Плоский текст Оферты — для выгрузки, сверки редакций и печати."""
    parts = [TITLE, SUBTITLE, f"Редакция {EDITION} от {EDITION_DATE}", ""]
    parts.extend(preamble(db))
    parts += ["", "1. Термины и определения:"]
    parts += [f"1.{i}. «{d['term']}» — {d['text']}"
              for i, d in enumerate(definitions(db), 1)]
    for s in sections(db):
        parts += ["", f"{s['n']}. {s['title']}", *s["clauses"]]
    r = requisites_block(db)
    parts += ["", f"{r['n']}. {r['title']}", *(r["lines"] or [r["note"]])]
    return "\n".join(parts)


def payload(db=None) -> dict:
    """Структура документа для страницы, мини-приложения, кабинета и тестов."""
    return {
        "edition": EDITION,
        "edition_date": EDITION_DATE,
        "title": TITLE,
        "subtitle": SUBTITLE,
        "product": PRODUCT,
        "operator": consent.operator_line(db),
        "contact": consent.requisites(db)["contact"] or CONTACT_DEFAULT,
        "requisites_complete": consent.requisites_complete(db),
        "preamble": preamble(db),
        "definitions": definitions(db),
        "sections": sections(db),
        "requisites": requisites_block(db),
        "consent_version": consent.CONSENT_VERSION,
        "page_path": PAGE_PATH,
        "text": full_text(db),
    }


