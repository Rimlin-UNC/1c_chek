def nds_name(rate, coded: bool = False) -> str:
    """Подпись ставки НДС.

    v1.70.93: коды тега 1199 расшифровываются по табл. 8 ФФД (vat_canonical), включая
    22 % и 22/122 с 2026 года; неоднозначное значение без источника показывается как
    есть — «значение N (ставка или код)».
    """
    key = vat_canonical(rate, coded)
    if key == "none":
        return "без НДС или не указано"
    if "/" in key and key in NDS_RATES:
        return key
    if coded or key not in VAT_BY_CODE:
        if key in NDS_RATES:
            return NDS_RATES[key]
    return f"значение {key} (ставка или код)"


def measure_name(code) -> str:
    """Единица измерения по коду ОКЕИ (или пустая строка)."""
    if code in (None, ""):
        return ""
    key = str(code).strip()
    return MEASURE_UNITS.get(key, "")


def foiv_name(code) -> str:
    """Название федерального органа по коду отраслевого реквизита."""
    key = str(code or "").strip()
    if not key:
        return ""
    return FOIV_CODES.get(key, f"федеральный орган, код {key}")
