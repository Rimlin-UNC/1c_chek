def product_type_name(code) -> str:
    """Название признака предмета расчёта по коду (или сам код)."""
    try:
        return PRODUCT_TYPES.get(int(code), f"код {code}")
    except (TypeError, ValueError):
        return str(code or "")


def payment_type_name(code) -> str:
    """Название способа расчёта по коду."""
    try:
        return PAYMENT_TYPES.get(int(code), f"код {code}")
    except (TypeError, ValueError):
        return str(code or "")


def taxation_name(code) -> str:
    """Система налогообложения по коду (маска)."""
    try:
        return TAXATION_TYPES.get(int(code), f"код {code}")
    except (TypeError, ValueError):
        return str(code or "")


def nds_name(rate) -> str:
    """Ставка НДС в человеческом виде."""
    key = str(rate if rate not in (None, "") else "none")
    return NDS_RATES.get(key, f"{key} %")


def measure_name(code) -> str:
    """Единица измерения по коду ОКЕИ (или пустая строка)."""
    if code in (None, ""):
        return ""
    key = str(code).strip()
    return MEASURE_UNITS.get(key, "")


def foiv_name(code) -> str:
    """Название федерального органа по коду отраслевого реквизита."""
    key = str(code or "").strip()
    if not key:
        return ""
    return FOIV_CODES.get(key, f"федеральный орган, код {key}")
