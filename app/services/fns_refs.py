# Код тега 1199 → ставка (табл. 8 ФФД). 7–10 — с 01.01.2025 (ставки УСН 5 % и 7 %);
# 11 и 12 — приказ ФНС от 08.12.2025 № ЕД-7-20/1050@, действуют с 05.01.2026.
VAT_BY_CODE = {"1": "20", "2": "10", "3": "20/120", "4": "10/110", "5": "0", "6": "none",
               "7": "5", "8": "7", "9": "5/105", "10": "7/107", "11": "22", "12": "22/122"}
# Значения, которые бывают ставками: 5, 7 и 10 совпадают с кодами — решает источник
_RATES = {"0", "5", "7", "10", "18", "20", "22", "5/105", "7/107", "10/110", "18/118",
          "20/120", "22/122", "none"}


def vat_canonical(value, coded: bool = False) -> str:
    """Ставка НДС в одном виде («20», «22/122», «none») — из кода тега 1199 или ставки.

    coded — значение пришло из фискальных данных (ответ ФНС или ОФД): число там —
    код тега 1199. Числа, которые ставками не бывают (1, 2, 3, 4, 6, 8, 9, 11, 12), —
    коды в любом случае. 5, 7 и 10 без coded считаются ставками (ручной ввод).
    """
    key = str(value).strip() if value not in (None, "") else "none"
    if key.lower() in ("none", "null"):
        return "none"
    if key.endswith(".0") and key[:-2].isdigit():          # 11.0 из JSON
        key = key[:-2]
    if key in VAT_BY_CODE and (coded or key not in _RATES):
        return VAT_BY_CODE[key]
    return key

