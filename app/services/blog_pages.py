@dataclass(frozen=True)
class Article:
    path: str
    title: str
    description: str
    h1: str
    keywords: tuple[str, ...]
    lead: str
    how_title: str
    steps: tuple[str, ...]
    how_extra: str
    not_found: str
    tool_title: str
    tool_items: tuple[str, ...]
    extra_title: str
    extra_paragraphs: tuple[str, ...]
    faq: tuple[tuple[str, str], ...]
    images: tuple[tuple[str, str], ...]
    up: tuple[str, str]
    side: tuple[str, str]
    down: tuple[str, str]
    cta: str


def _e(text: str) -> str:
    return html.escape(text or "", quote=True)


def _figure(src: str, alt: str, caption: str, eager: bool = False) -> str:
    loading = "eager" if eager else "lazy"
    return (f'<figure class="blog-figure"><img src="{_e(src)}" alt="{_e(alt)}" '
            f'width="1376" height="768" loading="{loading}" decoding="async">'
            f'<figcaption>{_e(caption)}</figcaption></figure>')


def _body(article: Article) -> str:
    steps = "".join(f"<li>{step}</li>" for step in article.steps)
    tool = "".join(f"<li>{item}</li>" for item in article.tool_items)
    extra = "".join(f"<p>{paragraph}</p>" for paragraph in article.extra_paragraphs)
    faq = "".join(f"<h3>{_e(question)}</h3><p>{answer}</p>" for question, answer in article.faq)
    return f"""
<section class="blog-how">
  <h2>{_e(article.how_title)}</h2>
  <ol class="steps">{steps}</ol>
  {article.how_extra}
</section>
<section class="blog-trust">
  <h2>Что делать, если чек не находится</h2>
  {article.not_found}
</section>
<section class="blog-tool">
  <h2>{_e(article.tool_title)}</h2>
  <ul>{tool}</ul>
</section>
<section class="blog-extra">
  <h2>{_e(article.extra_title)}</h2>
  {extra}
</section>
<section class="blog-faq">
  <h2>FAQ: частые вопросы</h2>
  {faq}
</section>
"""


