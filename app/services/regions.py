# Границы слова через lookaround, а не \b: в исходниках кириллица рядом
# с \b читается проверкой гомоглифов как латинская «b» внутри русского
# слова. Набор символов — тот же, что у \b для русских названий.
_WORD_L = r"(?<![а-яa-z0-9])"
_WORD_R = r"(?![а-яa-z0-9])"

# Прочие области — по прилагательному («Смоленская обл», «Тульская»).
for _code, _name in REGIONS.items():
    _base = _name.lower().replace("ё", "е")
    _m = re.match(r"([а-я-]+)ская область$", _base)
    if _m:
        _ADDRESS_RULES.append((_m.group(1) + r"ск\w*\s+(?:обл|область)", _code))


def region_name(code: str | None) -> str:
    """Название субъекта РФ по коду ('' если код неизвестен)."""
    key = re.sub(r"\D", "", str(code or ""))
    if len(key) == 1:
        key = "0" + key
    return REGIONS.get(key, "")


def region_from_inn(inn: str | None) -> tuple[str, str]:
    """Регион по ИНН продавца: первые две цифры — код налогового органа.

    Для ИНН из 10 (юрлицо) и 12 (ИП) цифр правило одинаковое. Если код
    неизвестен, возвращается (код, "") — код виден в интерфейсе, но
    название не выдумывается.
    """
    digits = re.sub(r"\D", "", str(inn or ""))
    if len(digits) not in (10, 12):
        return ("", "")
    code = digits[:2]
    return (code, REGIONS.get(code, ""))


def parse_address(address: str | None) -> dict:
    """Разобрать адрес места расчётов: индекс, регион, город.

    Возвращает словарь {postal, region_code, region_name, city};
    чего в адресе нет — пустая строка.
    """
    text = str(address or "").strip()
    out = {"postal": "", "region_code": "", "region_name": "", "city": ""}
    if not text:
        return out
    m = re.search(r"\b(\d{6})\b", text)
    if m:
        out["postal"] = m.group(1)
    low = text.lower().replace("ё", "е")
    for pattern, code in _ADDRESS_RULES:
        if re.search(_WORD_L + pattern + _WORD_R, low):
            out["region_code"] = code
            out["region_name"] = REGIONS.get(code, "")
            break
    # Кириллица и латиница — двумя ветками: символьный класс из обеих
    # письменностей сразу проверка гомоглифов считает смешанным токеном.
    m = re.search(r"(?:^|,\s*)(?:г\.?|город)\s*((?:[А-ЯЁ]|[A-Z])[\w\-. ]{1,40})",
                  text)
    if m:
        city = m.group(1).strip().strip(",.")
        out["city"] = re.sub(r"\s+", " ", city)[:60]
    return out


def detect(inn: str | None, address: str | None) -> dict:
    """Регион продавца: адрес главнее ИНН (адрес — место самой кассы).

    Если адрес не распознан, берём код из ИНН. В ответе всегда есть
    source: address | inn | "" — видно, откуда взялись данные.
    """
    addr = parse_address(address)
    inn_code, inn_name = region_from_inn(inn)
    # Города федерального значения — сами себе город (в адресе «г.» нет)
    if not addr["city"] and addr["region_code"] in ("77", "78", "92"):
        addr["city"] = REGIONS.get(addr["region_code"], "")
    if addr["region_code"]:
        return {"region_code": addr["region_code"],
                "region_name": addr["region_name"],
                "city": addr["city"], "postal": addr["postal"],
                "source": "address"}
    if inn_code:
        return {"region_code": inn_code, "region_name": inn_name,
                "city": addr["city"], "postal": addr["postal"],
                "source": "inn"}
    return {"region_code": "", "region_name": "", "city": "",
            "postal": "", "source": ""}
