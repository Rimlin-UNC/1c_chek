DEFAULT_INDUSTRY = "Прочие покупки"
DEFAULT_GROUP = "Прочее"


def _norm(text: str) -> str:
    return str(text or "").lower().replace("ё", "е")


def _hit(word: str, text: str) -> bool:
    """Слово-признак найдено как ОТДЕЛЬНОЕ слово, а не внутри другого.

    Без границы слова «провод» находился в «беспроводные», и наушники
    попадали в стройматериалы. Признаки, записанные с пробелом на конце
    («чай »), требуют продолжения — чтобы «чай» не ловил «чайник».
    """
    import re
    core = word.strip()
    if not core:
        return False
    left = r"(?<![а-яa-z0-9])"
    right = r"(?![а-яa-z0-9])" if word.endswith(" ") else ""
    return re.search(left + re.escape(core) + right, text) is not None


def classify_name(name: str, product_type=None) -> tuple[str, str]:
    """Отрасль и группа товаров по наименованию позиции.

    product_type: признак предмета расчёта ФНС (3 — работа, 4 — услуга);
    для услуг отрасль «Услуги» ставится без угадывания по словам.
    """
    try:
        pt = int(product_type) if product_type not in (None, "") else None
    except (TypeError, ValueError):
        pt = None
    low = _norm(name)
    # Признак предмета расчёта от ФНС главнее слов: работа и услуга — это
    # официальный код тега 1212, его не нужно угадывать по названию.
    if pt in (3, 4):
        return ("Услуги", "Услуги")
    for industry, group, words in RULES:
        for word in words:
            if _hit(word, low):
                return (industry, group)
    return (DEFAULT_INDUSTRY, DEFAULT_GROUP)


def classify_items(items: list[dict]) -> dict:
    """Отрасль чека по позициям: побеждает группа с наибольшей суммой.

    items: [{"name": ..., "total": ..., "product_type": ...}, ...]
    Возвращает {industry, group, shares: [{group, sum, count}], source}.
    """
    sums: dict[str, float] = {}
    counts: dict[str, int] = {}
    industries: dict[str, str] = {}
    for it in items or []:
        if not isinstance(it, dict):
            continue
        industry, group = classify_name(it.get("name", ""),
                                        it.get("product_type"))
        try:
            total = float(it.get("total") or 0)
        except (TypeError, ValueError):
            total = 0.0
        sums[group] = sums.get(group, 0.0) + total
        counts[group] = counts.get(group, 0) + 1
        industries[group] = industry
    if not sums:
        return {"industry": "", "group": "", "shares": [], "source": ""}
    # Побеждает группа с наибольшей суммой; при равенстве — где больше
    # позиций; при полном равенстве — «Прочее» последним (порядок RULES).
    best = max(sums, key=lambda g: (sums[g], counts[g], -len(g)))
    shares = [{"group": g, "industry": industries[g],
               "sum": round(sums[g], 2), "count": counts[g]}
              for g in sorted(sums, key=lambda g: -sums[g])]
    return {"industry": industries[best], "group": best,
            "shares": shares, "source": "names"}


def industries() -> list[str]:
    """Список отраслей для выпадающих фильтров (без дублей, по порядку)."""
    out: list[str] = []
    for industry, _group, _words in RULES:
        if industry not in out:
            out.append(industry)
    out.append(DEFAULT_INDUSTRY)
    return out


def groups() -> list[str]:
    """Список групп товаров для фильтров."""
    out: list[str] = []
    for _industry, group, _words in RULES:
        if group not in out:
            out.append(group)
    out.append(DEFAULT_GROUP)
    return out
